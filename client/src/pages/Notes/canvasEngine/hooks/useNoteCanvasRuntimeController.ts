import { useNoteCanvasLayerProps } from './useNoteCanvasLayerProps';
import { useNoteCanvasRuntime } from './useNoteCanvasRuntime';
import { useRuntimeBlockOperationsController } from './useRuntimeBlockOperationsController';
import { useRuntimeDocumentDataController } from './useRuntimeDocumentDataController';
import { useRuntimeFrameModelController } from './useRuntimeFrameModelController';
import { useRuntimeLayoutModelController } from './useRuntimeLayoutModelController';
import { useRuntimeSurfaceStateController } from './useRuntimeSurfaceStateController';

export function useNoteCanvasRuntimeController() {
  const { noteId } = useNoteCanvasRuntime();
  const {
    activeBlockId,
    blockListRef,
    chromeCollapsed,
    clearBlockSelection,
    closeOverlay,
    collapseChrome,
    expandChrome,
    focusBlockId,
    interactionState,
    layoutMode,
    markBlockFocused,
    markBlockSelected,
    movingBlockIdRef,
    pageOffsetX,
    selectedBlockId,
    setActiveBlockId,
    setFocusBlockId,
    setInteractionState,
    setLayoutMode,
    setSelectedBlockId,
    setSnapGuide,
    snapEnabled,
    snapGuide,
    showAdvancedInsert,
    showExportPreview,
    showMoreActions,
    showNoteInfo,
    showPreviewAIVisibility,
    showPreviewBlockTypes,
    showPreviewExportStatus,
    suppressMeasuredReflowUntilRef,
    surfaceMode,
    surfacePolicy,
    toggleAdvancedInsert,
    toggleExportPreview,
    toggleLayoutMode,
    toggleMoreActions,
    toggleNoteInfo,
    togglePreviewAIVisibility,
    togglePreviewBlockTypes,
    togglePreviewExportStatus,
    toggleSnapEnabled,
    toggleSurfaceMode,
  } = useRuntimeSurfaceStateController();
  const {
    applyMeasuredBlockHeightDraft,
    note,
    blocks,
    sortedBlocks,
    loading,
    titleDraft,
    setTitleDraft,
    newTemplateId,
    setNewTemplateId,
    templateOptions,
    templateWarning,
    newBlockText,
    setNewBlockText,
    savingBlockId,
    anchorsBySourceRef,
    sourceJumpTarget,
    setSourceJumpTarget,
    sourceJumpBusy,
    blockTextDrafts,
    setBlockTextDrafts,
    blockFieldDrafts,
    setBlockFieldDrafts,
    defaultTextTemplate,
    insertTemplateGroups,
    insertTemplateOptions,
    saveTitle,
    createBlock,
    saveBlock,
    applyTemplateToBlock,
    persistBlockLayout,
    toggleBlockExportRole,
    toggleBlockAIVisibility,
    addBlock,
    trashBlock,
    restoreBlock,
    handleViewSource,
    layoutDrafts,
    mergeLayoutDrafts,
    setLayoutDrafts,
    sourceReferenceCount,
  } = useRuntimeDocumentDataController({
    clearBlockSelection,
    noteId,
  });

  const {
    blockLayouts,
    contentWidth,
    defaultDraftLayout,
    persistChangedBlockLayouts,
    persistLayoutSnapshot,
    visibleBlocks,
  } = useRuntimeLayoutModelController({
    blocks,
    blockListRef,
    layoutDrafts,
    pageOffsetX,
    persistBlockLayout,
    sortedBlocks,
    surfaceMode,
    surfacePolicy,
  });

  const {
    activateDraft,
    clearSlashTarget,
    creatingDraft,
    discardDraft,
    draftActive,
    draftLayout,
    draftRef,
    draftText,
    handleBlockKeyDown,
    handleBlockListMouseDown,
    handleBlockTextChange,
    handleDraftChange,
    handleDraftKeyDown,
    handleTrashBlock,
    handlePageSpaceDoubleClick,
    handleSelectSlashCommand,
    handleSurfacePointerDown,
    handleMeasuredBlockHeight,
    persistDraft,
    resizeDraftFromTextarea,
    slashCommands,
    slashTarget,
    updateBlockFieldDraft,
    beginMoveBlock,
    beginResizeBlock,
  } = useRuntimeBlockOperationsController({
    applyLayoutDrafts: mergeLayoutDrafts,
    applyMeasuredBlockHeightDraft,
    applyTemplateToBlock,
    blockLayouts,
    blockListRef,
    blocks,
    blockTextDrafts,
    clearBlockSelection,
    contentWidth,
    createBlock,
    defaultDraftLayout,
    defaultTextTemplate,
    insertTemplateOptions,
    movingBlockIdRef,
    note,
    orderedBlocks: visibleBlocks,
    pageOffsetX,
    persistChangedBlockLayouts,
    persistLayoutSnapshot,
    restoreBlockForHistory: restoreBlock,
    saveBlock,
    setBlockFieldDrafts,
    setBlockTextDrafts,
    setActiveBlockId,
    setFocusBlockId,
    setInteractionState,
    setLayoutDrafts,
    setLayoutMode,
    setSelectedBlockId,
    setSnapGuide,
    snapEnabled,
    suppressMeasuredReflowUntilRef,
    surfacePolicy,
    templateOptions,
    trashBlock,
  });

  const {
    exportPreview,
    noteCanvasRuntime,
    pageContentHeight,
    primaryPageFrame,
  } = useRuntimeFrameModelController({
    blockLayouts,
    defaultDraftLayout,
    draftActive,
    draftLayout,
    pageOffsetX,
    surfaceMode,
    visibleBlocks,
  });

  const layerProps = useNoteCanvasLayerProps({
    activeBlockId,
    anchorsBySourceRef,
    blockFieldDrafts,
    blockLayouts,
    blockListRef,
    blockTextDrafts,
    chromeCollapsed,
    creatingDraft,
    defaultDraftLayout,
    draftActive,
    draftLayout,
    draftRef,
    draftText,
    exportPreview,
    focusBlockId,
    insertTemplateGroups,
    interactionState,
    layoutMode,
    newBlockText,
    newTemplateId,
    note,
    noteCanvasRuntime,
    pageContentHeight,
    pageOffsetX,
    primaryPageFrameX: primaryPageFrame.x,
    primaryPageFrameWidth: primaryPageFrame.width,
    savingBlockId,
    selectedBlockId,
    setSourceJumpTarget,
    showAdvancedInsert,
    showExportPreview,
    showMoreActions,
    showNoteInfo,
    showPreviewAIVisibility,
    showPreviewBlockTypes,
    showPreviewExportStatus,
    slashCommands,
    slashTarget,
    snapEnabled,
    snapGuide,
    sortedBlockCount: sortedBlocks.length,
    sourceJumpBusy,
    sourceJumpTarget,
    sourceReferenceCount,
    surfaceMode,
    surfacePolicy,
    surfacePolicyMode: surfacePolicy.mode,
    templateWarning,
    titleDraft,
    visibleBlocks,
    onActivateDraft: activateDraft,
    onAddBlock: addBlock,
    onBeginMoveBlock: beginMoveBlock,
    onBeginResizeBlock: beginResizeBlock,
    onBlockKeyDown: handleBlockKeyDown,
    onBlockListMouseDown: handleBlockListMouseDown,
    onBlockTextChange: handleBlockTextChange,
    onClearSlashTarget: clearSlashTarget,
    onCloseOverlay: closeOverlay,
    onCollapseChrome: collapseChrome,
    onDiscardDraft: discardDraft,
    onDraftChange: handleDraftChange,
    onDraftKeyDown: handleDraftKeyDown,
    onExpandChrome: expandChrome,
    onFieldDraftChange: updateBlockFieldDraft,
    onFloatingPanelFocusBlock: setFocusBlockId,
    onMeasuredBlockHeight: handleMeasuredBlockHeight,
    onNewBlockTextChange: setNewBlockText,
    onNewTemplateChange: setNewTemplateId,
    onPageSpaceDoubleClick: handlePageSpaceDoubleClick,
    onPersistDraft: persistDraft,
    onResizeDraftFromTextarea: resizeDraftFromTextarea,
    onSaveBlock: saveBlock,
    onSaveTitle: saveTitle,
    onSelectBlock: markBlockSelected,
    onSelectSlashCommand: handleSelectSlashCommand,
    onSurfacePointerDown: handleSurfacePointerDown,
    onTitleDraftChange: setTitleDraft,
    onToggleAdvancedInsert: toggleAdvancedInsert,
    onToggleAIVisibility: toggleBlockAIVisibility,
    onToggleExportPreview: toggleExportPreview,
    onToggleExportRole: toggleBlockExportRole,
    onToggleLayoutMode: toggleLayoutMode,
    onToggleMoreActions: toggleMoreActions,
    onToggleNoteInfo: toggleNoteInfo,
    onTogglePreviewAIVisibility: togglePreviewAIVisibility,
    onTogglePreviewBlockTypes: togglePreviewBlockTypes,
    onTogglePreviewExportStatus: togglePreviewExportStatus,
    onToggleSnapEnabled: toggleSnapEnabled,
    onToggleSurfaceMode: toggleSurfaceMode,
    onTrashBlock: handleTrashBlock,
    onViewSource: handleViewSource,
    onWritingSurfaceFocusBlock: markBlockFocused,
  });

  return {
    layerProps,
    loading,
    note,
  };
}
